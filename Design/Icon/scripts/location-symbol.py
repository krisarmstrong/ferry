#!/usr/bin/env python3
"""Writes the Finder location symbol from the 18 pt menu bar glyph.

    python3 Design/Icon/scripts/location-symbol.py     (run from the repository root)

Finder shows a FileProvider domain in its sidebar with the symbol its extension names in
CFBundleIcons > CFBundlePrimaryIcon > CFBundleSymbolName. This turns MenuBarGlyph-18.svg into
an SF Symbols template (one Regular, medium-scale glyph; the system derives the other weights
and scales from it) in the extension's asset catalog.
"""

import re
from pathlib import Path

ROOT = Path.cwd()
SOURCE = ROOT / "Design/Icon/MenuBarGlyph-18.svg"
TARGET = ROOT / "Apps/FerryProvider/Assets.xcassets/ferry.location.symbolset"

# Glyph units to symbol units: 18 pt glyph rows 2..15 become 6 units each, the keel (row 15)
# on the baseline, so the glyph stands 78 units tall against the 70.5 unit cap height.
SCALE = 6.0
LEFT = 1.0
KEEL = 15.0
WIDTH = (17.0 - LEFT) * SCALE
ORIGIN_X = 1391.0
MARGIN = 6.0


def transform(path: str) -> str:
    out = []
    for command, args in re.findall(r"([MHVLQZ])([^MHVLQZ]*)", path):
        numbers = [float(n) for n in args.replace(",", " ").split()]
        if command in "ML Q":
            coords = []
            for x, y in zip(numbers[0::2], numbers[1::2]):
                coords += [f"{(x - LEFT) * SCALE:g}", f"{(y - KEEL) * SCALE:g}"]
            out.append(command + " ".join(coords))
        elif command == "H":
            out.append("H" + " ".join(f"{(x - LEFT) * SCALE:g}" for x in numbers))
        elif command == "V":
            out.append("V" + " ".join(f"{(y - KEEL) * SCALE:g}" for y in numbers))
        else:
            out.append("Z")
    return " ".join(out)


paths = re.findall(r'<path d="([^"]+)"', SOURCE.read_text())
shapes = "\n".join(f'      <path d="{transform(p)}"/>' for p in paths)
left = ORIGIN_X - MARGIN
right = ORIGIN_X + WIDTH + MARGIN

svg = f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by Design/Icon/scripts/location-symbol.py from MenuBarGlyph-18.svg. Do not edit. -->
<svg version="1.1" xmlns="http://www.w3.org/2000/svg" width="3300" height="2200">
 <g id="Notes">
  <text id="template-version" x="18" y="40" style="font-family:'LucidaGrande';font-size:13">Template v.5.0</text>
 </g>
 <g id="Guides">
  <line id="Baseline-S" x1="263" x2="3036" y1="696" y2="696" style="fill:none;stroke:#27AAE1;stroke-width:0.5"/>
  <line id="Capline-S" x1="263" x2="3036" y1="625.541" y2="625.541" style="fill:none;stroke:#27AAE1;stroke-width:0.5"/>
  <line id="Baseline-M" x1="263" x2="3036" y1="1126" y2="1126" style="fill:none;stroke:#27AAE1;stroke-width:0.5"/>
  <line id="Capline-M" x1="263" x2="3036" y1="1055.54" y2="1055.54" style="fill:none;stroke:#27AAE1;stroke-width:0.5"/>
  <line id="Baseline-L" x1="263" x2="3036" y1="1556" y2="1556" style="fill:none;stroke:#27AAE1;stroke-width:0.5"/>
  <line id="Capline-L" x1="263" x2="3036" y1="1485.54" y2="1485.54" style="fill:none;stroke:#27AAE1;stroke-width:0.5"/>
  <line id="left-margin-Regular-M" x1="{left:g}" x2="{left:g}" y1="1030.79" y2="1150.12" style="fill:none;stroke:#00AEEF;stroke-width:0.5"/>
  <line id="right-margin-Regular-M" x1="{right:g}" x2="{right:g}" y1="1030.79" y2="1150.12" style="fill:none;stroke:#00AEEF;stroke-width:0.5"/>
 </g>
 <g id="Symbols">
  <g id="Regular-M" transform="matrix(1 0 0 1 {ORIGIN_X:g} 1126)">
{shapes}
  </g>
 </g>
</svg>
"""

TARGET.mkdir(parents=True, exist_ok=True)
(TARGET / "ferry.location.svg").write_text(svg)
(TARGET / "Contents.json").write_text(
    '{\n  "info" : {\n    "author" : "xcode",\n    "version" : 1\n  },\n'
    '  "symbols" : [\n    {\n      "filename" : "ferry.location.svg",\n'
    '      "idiom" : "universal"\n    }\n  ]\n}\n'
)
catalog = TARGET.parent / "Contents.json"
if not catalog.exists():
    catalog.write_text('{\n  "info" : {\n    "author" : "xcode",\n    "version" : 1\n  }\n}\n')
print(f"Wrote {TARGET}")
